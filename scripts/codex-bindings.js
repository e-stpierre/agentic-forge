// Regenerates the typed Codex app-server bindings in src/runtimes/codex-protocol/.
//
// Runs `codex app-server generate-ts --experimental` into a temp dir, then
// copies only the types the session driver uses (and the types they import),
// with `.js` import extensions for Node16 module resolution. The Codex
// version is recorded in `version.ts`; the driver is tested against it.
//
// Usage: node scripts/codex-bindings.js [--codex <command>]

import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src", "runtimes", "codex-protocol");

/** Root types of the driver (paths relative to the generated dir, without `.ts`). */
const ROOTS = [
	"InitializeParams",
	"InitializeResponse",
	"RequestId",
	"v2/ThreadStartParams",
	"v2/ThreadStartResponse",
	"v2/ThreadResumeParams",
	"v2/ThreadResumeResponse",
	"v2/TurnStartParams",
	"v2/TurnStartResponse",
	"v2/TurnSteerParams",
	"v2/TurnSteerResponse",
	"v2/TurnInterruptParams",
	"v2/UserInput",
	"v2/ThreadItem",
	"v2/ItemStartedNotification",
	"v2/ItemCompletedNotification",
	"v2/TurnStartedNotification",
	"v2/TurnCompletedNotification",
	"v2/ErrorNotification",
	"v2/SkillsListParams",
	"v2/SkillsListResponse",
	"v2/CommandExecutionRequestApprovalParams",
	"v2/CommandExecutionRequestApprovalResponse",
	"v2/FileChangeRequestApprovalParams",
	"v2/FileChangeRequestApprovalResponse",
	"v2/PermissionsRequestApprovalParams",
	"v2/PermissionsRequestApprovalResponse",
	"v2/ToolRequestUserInputParams",
	"v2/ToolRequestUserInputResponse",
	"v2/McpServerElicitationRequestResponse",
];

const codexIndex = process.argv.indexOf("--codex");
const codex = codexIndex > 0 ? process.argv[codexIndex + 1] : "codex";
const shell = process.platform === "win32";

const version = execFileSync(codex, ["--version"], { encoding: "utf-8", shell })
	.trim()
	.replace(/^codex-cli\s+/, "");
const tmp = mkdtempSync(join(tmpdir(), "codex-ts-"));
try {
	execFileSync(codex, ["app-server", "generate-ts", "--experimental", "--out", tmp], {
		stdio: "ignore",
		shell,
	});

	const files = new Map();
	const queue = [...ROOTS];
	while (queue.length > 0) {
		const name = queue.shift();
		if (files.has(name)) continue;
		const source = readFileSync(join(tmp, `${name}.ts`), "utf-8");
		const dir = posix.dirname(name);
		const rewritten = source.replace(/from "(\.{1,2}\/[^"]+)"/g, (_match, spec) => {
			queue.push(posix.normalize(posix.join(dir, spec)));
			return `from "${spec}.js"`;
		});
		files.set(name, rewritten);
	}

	rmSync(outDir, { recursive: true, force: true });
	for (const [name, source] of files) {
		const target = join(outDir, `${name}.ts`);
		mkdirSync(dirname(target), { recursive: true });
		writeFileSync(target, source, "utf-8");
	}
	const exports = ROOTS.map((name) => {
		const type = posix.basename(name);
		return `export type { ${type} } from "./${name}.js";`;
	});
	writeFileSync(
		join(outDir, "index.ts"),
		`// GENERATED by scripts/codex-bindings.js from codex ${version}. Do not edit.\n${exports.join("\n")}\n`,
		"utf-8",
	);
	writeFileSync(
		join(outDir, "version.ts"),
		`// GENERATED by scripts/codex-bindings.js. Do not edit.\n\n/** Codex CLI version the app-server bindings were generated from and tested with. */\nexport const CODEX_PROTOCOL_VERSION = "${version}";\n`,
		"utf-8",
	);
	console.log(`Wrote ${files.size} types from codex ${version} to ${outDir}`);
} finally {
	rmSync(tmp, { recursive: true, force: true });
}
