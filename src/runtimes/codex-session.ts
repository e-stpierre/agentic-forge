/** A line-based connection to an app-server (a process, or a fake in tests). */
export interface AppServerTransport {
	write(line: string): void;
	onLine(listener: (line: string) => void): void;
	/** Called once when the server is gone, with its exit code and the end of its stderr. */
	onExit(listener: (code: number | null, stderr: string) => void): void;
	/** Ends the input; the server exits on its own. */
	close(): void;
	/** Kills the server and its process tree. */
	kill(): void;
}

export interface AppServerSpawnOptions {
	args: string[];
	cwd: string | null;
	env: NodeJS.ProcessEnv;
}

/** Spawns `codex app-server` with stdio pipes (resolves a Windows `.cmd` shim to node). */
export function spawnAppServer(options: AppServerSpawnOptions): AppServerTransport {
	let exe = getExecutable("codex");
	let args = ["app-server", ...options.args];
	if (process.platform === "win32" && /\.(cmd|bat)$/i.test(exe)) {
		const script = resolveCmdScript(exe);
		if (script) {
			args = [script, ...args];
			exe = process.execPath;
		}
	}
	const proc: ChildProcess = spawn(exe, args, {
		cwd: options.cwd ?? undefined,
		env: options.env,
		stdio: ["pipe", "pipe", "pipe"],
		...treeSpawnOptions(),
	});
	let stderr = "";
	proc.stderr?.on("data", (chunk: Buffer) => {
		stderr = (stderr + chunk.toString("utf-8")).slice(-4000);
	});
	const exitListeners: ((code: number | null, stderr: string) => void)[] = [];
	let exited = false;
	const onGone = (code: number | null) => {
		if (exited) return;
		exited = true;
		for (const listener of exitListeners) listener(code, stderr);
	};
	proc.on("error", (err) => {
		stderr += err.message;
		onGone(null);
	});
	proc.on("close", (code) => onGone(code));
	const lines = proc.stdout ? readline.createInterface({ input: proc.stdout }) : null;
	return {
		write: (line) => {
			if (proc.stdin?.writable) proc.stdin.write(`${line}\n`);
		},
		onLine: (listener) => lines?.on("line", listener),
		onExit: (listener) => exitListeners.push(listener),
		close: () => proc.stdin?.end(),
		kill: () => killProcessTree(proc.pid),
	};
}

