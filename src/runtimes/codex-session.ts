/**
 * Codex session driver on `codex app-server` (JSON-RPC over stdio JSONL).
 *
 * One app-server process per session, one thread per session (the thread id
 * is the session id, also used by `codex exec resume`). Each user message
 * starts a turn (`turn/start`); `steer` adds input to the running turn
 * (`turn/steer`), `interrupt` stops it (`turn/interrupt`). Command and file
 * change approvals, permission requests and `item/tool/requestUserInput`
 * become session requests (`needs_input`) while the session waits alive.
 * Command approvals matching the step allowlist (`Bash`, `Bash(git *)`) and
 * file change approvals with `Edit`/`Write` in it are accepted without asking.
 *
 * The app-server uses the user's Codex login; this driver never reads or
 * passes Codex credentials. Typed bindings: `codex-protocol/` (generated by
 * `scripts/codex-bindings.js`, version in `CODEX_PROTOCOL_VERSION`).
 */

