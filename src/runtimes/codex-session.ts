interface RpcMessage {
	id?: string | number;
	method?: string;
	params?: unknown;
	result?: unknown;
	error?: { code?: number; message?: string };
}

/** Minimal JSON-RPC client (the app-server omits the `jsonrpc` field). */
class RpcClient {
	private seq = 0;
	private readonly waiting = new Map<
		string | number,
		{ resolve: (value: unknown) => void; reject: (err: Error) => void }
	>();

	constructor(
		private readonly transport: AppServerTransport,
		private readonly onNotification: (method: string, params: unknown) => void,
		private readonly onRequest: (method: string, params: unknown) => Promise<unknown>,
	) {
		transport.onLine((line) => this.receive(line));
	}

	request<T>(method: string, params: unknown): Promise<T> {
		this.seq += 1;
		const id = this.seq;
		return new Promise<T>((resolve, reject) => {
			this.waiting.set(id, { resolve: resolve as (value: unknown) => void, reject });
			this.transport.write(JSON.stringify({ id, method, params }));
		});
	}

	notify(method: string, params?: unknown): void {
		this.transport.write(JSON.stringify(params === undefined ? { method } : { method, params }));
	}

	/** Rejects every request still waiting (the server is gone). */
	fail(error: Error): void {
		for (const waiter of this.waiting.values()) waiter.reject(error);
		this.waiting.clear();
	}

	private receive(line: string): void {
		const trimmed = line.trim();
		if (!trimmed.startsWith("{")) return;
		let message: RpcMessage;
		try {
			message = JSON.parse(trimmed) as RpcMessage;
		} catch {
			return;
		}
		if (message.method && message.id !== undefined) {
			const id = message.id;
			this.onRequest(message.method, message.params).then(
				(result) => this.transport.write(JSON.stringify({ id, result })),
				(err: Error) =>
					this.transport.write(
						JSON.stringify({ id, error: { code: -32601, message: err.message } }),
					),
			);
			return;
		}
		if (message.method) {
			this.onNotification(message.method, message.params);
			return;
		}
		if (message.id === undefined) return;
		const waiter = this.waiting.get(message.id);
		if (!waiter) return;
		this.waiting.delete(message.id);
		if (message.error) {
			waiter.reject(new Error(message.error.message ?? `JSON-RPC error ${message.error.code}`));
		} else {
			waiter.resolve(message.result);
		}
	}
}

/** Command a permission request names (`shell` commands, file changes). */
const SHELL_TOOL = "shell";
const PATCH_TOOL = "apply_patch";
const PERMISSIONS_TOOL = "request_permissions";
const QUESTION_TOOL = "request_user_input";
const OPTION_IDS = "abcdefghij";

/**
 * True when a shell command is approved by an allowlist rule: `Bash` or
 * `Bash(*)` (every command), `Bash(<prefix> *)` or `Bash(<prefix>:*)` (a
 * prefix), `Bash(<command>)` (exact). `shell` is accepted as an alias.
 */
export function commandAllowed(command: string, rules: string[] | null | undefined): boolean {
	const cmd = command.trim();
	for (const rule of rules ?? []) {
		const match = /^(Bash|shell)(?:\((.*)\))?$/.exec(rule.trim());
		if (!match) continue;
		const pattern = match[2]?.trim();
		if (!pattern || pattern === "*") return true;
		if (pattern.endsWith(":*") || pattern.endsWith(" *")) {
			const head = pattern.slice(0, -2).trim();
			if (cmd === head || cmd.startsWith(`${head} `)) return true;
		} else if (pattern.endsWith("*")) {
			if (cmd.startsWith(pattern.slice(0, -1))) return true;
		} else if (cmd === pattern) {
			return true;
		}
	}
	return false;
}

/** True when the allowlist approves file edits (`Edit`, `Write`, `MultiEdit`). */
export function editsAllowed(rules: string[] | null | undefined): boolean {
	return (rules ?? []).some((rule) => /^(Edit|Write|MultiEdit)$/.test(rule.trim()));
}

/** Turn input of a user message: text, then local images. */
export function codexUserInput(text: string, images: string[] = []): UserInput[] {
	const input: UserInput[] = [];
	if (text) input.push({ type: "text", text, text_elements: [] });
	for (const image of images) input.push({ type: "localImage", path: image });
	return input;
}

/**
 * Normalized events of an app-server thread item: messages, tool calls
 * (`item/started`) and results (`item/completed`) for commands, MCP and
 * dynamic tool calls and web searches, and one diff per changed file.
 */
export function codexItemEvents(item: ThreadItem, done: boolean): SessionEvent[] {
	switch (item.type) {
		case "agentMessage":
			if (!done) return [];
			return [
				{
					type: "item",
					id: item.id,
					kind: "message",
					status: "completed",
					role: "assistant",
					text: item.text,
				},
			];
		case "commandExecution": {
			if (!done) {
				return [
					{
						type: "item",
						id: item.id,
						kind: "tool_call",
						status: "started",
						tool: SHELL_TOOL,
						input: { command: item.command, cwd: item.cwd },
					},
				];
			}
			const failed =
				item.status === "failed" ||
				item.status === "declined" ||
				(typeof item.exitCode === "number" && item.exitCode !== 0);
			return [
				{
					type: "item",
					id: item.id,
					kind: "tool_result",
					status: "completed",
					tool: SHELL_TOOL,
					text: item.aggregatedOutput ?? (item.status === "declined" ? "Declined" : ""),
					isError: failed,
				},
			];
		}
		case "mcpToolCall":
		case "dynamicToolCall": {
			const tool = item.type === "mcpToolCall" ? `${item.server}.${item.tool}` : item.tool;
			if (!done) {
				const args =
					item.arguments && typeof item.arguments === "object" && !Array.isArray(item.arguments)
						? (item.arguments as Record<string, unknown>)
						: { arguments: item.arguments };
				return [
					{ type: "item", id: item.id, kind: "tool_call", status: "started", tool, input: args },
				];
			}
			const output =
				item.type === "mcpToolCall"
					? (item.error?.message ?? item.result ?? "")
					: (item.contentItems ?? "");
			const failed =
				item.status === "failed" || (item.type === "dynamicToolCall" && item.success === false);
			return [
				{
					type: "item",
					id: item.id,
					kind: "tool_result",
					status: "completed",
					tool,
					text: typeof output === "string" ? output : JSON.stringify(output),
					isError: failed,
				},
			];
		}
		case "webSearch":
			if (done) return [];
			return [
				{
					type: "item",
					id: item.id,
					kind: "tool_call",
					status: "started",
					tool: "web_search",
					input: { query: item.query },
				},
			];
		case "fileChange":
			if (!done) return [];
			return item.changes.map((change, index) => ({
				type: "diff" as const,
				id: `${item.id}:${index}`,
				path: change.path,
				change: change.kind.type,
				...(change.diff ? { patch: change.diff } : {}),
			}));
		default:
			return [];
	}
}

/** Codex skill matching an af skill id: exact name, then the name after the plugin prefix. */
export function findCodexSkill(
	id: string,
	list: SkillsListResponse,
): { name: string; path: string } | null {
	const skills = list.data.flatMap((entry) => entry.skills).filter((s) => s.enabled !== false);
	const exact = skills.find((s) => s.name === id);
	if (exact) return { name: exact.name, path: exact.path };
	const short = id.includes(":") ? id.slice(id.indexOf(":") + 1) : null;
	const byShort = short ? skills.find((s) => s.name === short) : undefined;
	return byShort ? { name: byShort.name, path: byShort.path } : null;
}

interface QueuedMessage {
	id: string;
	text: string;
	images: string[];
	/** Native skill input sent before the text (first turn of a skill step). */
	skill?: { name: string; path: string };
}

export class CodexSession implements RuntimeSession {
	readonly runtime = "codex" as const;
	sessionId: string | null = null;
	state: SessionState = "starting";
	readonly done: Promise<Error | null>;

	private readonly listener: SessionListener;
	private readonly spawnServer: (options: AppServerSpawnOptions) => AppServerTransport;
	private readonly pending = new Map<string, (decision: SessionDecision) => void>();
	private readonly queue: QueuedMessage[] = [];
	/** Turns whose `turn/completed` arrived (it can precede the `turn/start` response). */
	private readonly completedTurns = new Set<string>();
	private transport: AppServerTransport | null = null;
	private rpc: RpcClient | null = null;
	private options: SessionStartOptions | null = null;
	private started = false;
	private ready = false;
	private closing = false;
	private turnId: string | null = null;
	private turnStarting = false;
	private turnText: string | null = null;
	private failure: Error | null = null;
	private finished = false;
	private settle: (error: Error | null) => void = () => {};

	constructor(
		listener: SessionListener,
		spawnServer: (options: AppServerSpawnOptions) => AppServerTransport = (o) =>
			codexAppServer.spawn(o),
	) {
		this.listener = listener;
		this.spawnServer = spawnServer;
		this.done = new Promise((resolve) => {
			this.settle = resolve;
		});
	}

	start(options: SessionStartOptions): void {
		if (this.started) throw new Error("Session already started");
		this.started = true;
		this.options = options;
		void this.run(options);
	}

	resume(sessionId: string, options: SessionStartOptions): void {
		this.start({ ...options, resume: sessionId });
	}

	send(text: string): string {
		const id = randomUUID();
		this.queue.push({ id, text, images: [] });
		if (this.state === "idle") this.setState("running");
		this.pump();
		return id;
	}

	steer(text: string): string {
		const turnId = this.turnId;
		if (!turnId || !this.rpc || !this.sessionId) return this.send(text);
		const id = randomUUID();
		const params: TurnSteerParams = {
			threadId: this.sessionId,
			input: codexUserInput(text),
			expectedTurnId: turnId,
		};
		// The turn may end before the steer arrives: the message then starts the next turn
		this.rpc.request("turn/steer", params).catch(() => {
			this.queue.push({ id, text, images: [] });
			this.pump();
		});
		return id;
	}

	async interrupt(): Promise<void> {
		if (!this.rpc || !this.sessionId || !this.turnId) return;
		const params: TurnInterruptParams = { threadId: this.sessionId, turnId: this.turnId };
		await this.rpc.request("turn/interrupt", params).catch(() => undefined);
	}

	respond(requestId: string, decision: SessionDecision): void {
		const resolve = this.pending.get(requestId);
		if (!resolve) return;
		this.pending.delete(requestId);
		this.emit({ type: "request.resolved", id: requestId, decision });
		if (this.pending.size === 0 && this.state === "awaiting-input") this.setState("running");
		resolve(decision);
	}

	close(): void {
		if (this.closing) return;
		this.closing = true;
		this.queue.length = 0;
		const transport = this.transport;
		if (!transport) {
			this.finish();
			return;
		}
		transport.close();
		// The app-server exits when its input ends; force it after a grace period
		setTimeout(() => transport.kill(), 2000).unref?.();
	}

	private async run(options: SessionStartOptions): Promise<void> {
		const onAbort = () => {
			void this.interrupt();
			this.closing = true;
			this.transport?.kill();
			if (!this.transport) this.finish();
		};
		if (options.signal?.aborted) {
			onAbort();
			return;
		}
		options.signal?.addEventListener("abort", onAbort, { once: true });
		void this.done.then(() => options.signal?.removeEventListener("abort", onAbort));
		try {
			const transport = this.spawnServer({
				args: [],
				cwd: options.cwd ?? null,
				env: { ...(options.env ?? process.env) },
			});
			this.transport = transport;
			this.rpc = new RpcClient(
				transport,
				(method, params) => this.onNotification(method, params),
				(method, params) => this.onServerRequest(method, params),
			);
			transport.onExit((code, stderr) => {
				if (!this.closing && !this.failure) {
					const tail = stderr.trim().split(/\r?\n/).slice(-3).join("\n");
					this.failure = new Error(
						`codex app-server exited${code === null ? "" : ` with code ${code}`}${tail ? `: ${tail}` : ""}`,
					);
				}
				this.rpc?.fail(new Error("codex app-server exited"));
				this.finish();
			});
			if (this.closing) return;
			await this.handshake(options);
		} catch (err) {
			const error = err instanceof Error ? err : new Error(String(err));
			if (!this.closing) {
				this.failure = error;
				this.emit({ type: "error", message: error.message });
			}
			this.closing = true;
			if (this.transport) this.transport.kill();
			else this.finish();
		}
	}

	private async handshake(options: SessionStartOptions): Promise<void> {
		const rpc = this.rpc as RpcClient;
		const init: InitializeParams = {
			clientInfo: {
				name: "agentic-forge",
				title: "agentic-forge",
				version: CODEX_PROTOCOL_VERSION,
			},
			capabilities: { experimentalApi: true },
		};
		await rpc.request("initialize", init);
		rpc.notify("initialized");

		const sandbox = options.bypassPermissions
			? "danger-full-access"
			: ((options.sandbox ?? "workspace-write") as ThreadStartParams["sandbox"]);
		const common = {
			cwd: options.cwd ?? null,
			model: options.model ?? null,
			approvalPolicy: options.bypassPermissions ? ("never" as const) : ("on-request" as const),
			sandbox,
			config: this.threadConfig(options, sandbox),
			developerInstructions: options.appendSystemPrompt ?? null,
			persistExtendedHistory: false,
		};
		let response: ThreadStartResponse;
		if (options.resume) {
			const params: ThreadResumeParams = { threadId: options.resume, ...common };
			response = await rpc.request<ThreadStartResponse>("thread/resume", params);
		} else {
			const params: ThreadStartParams = { ...common, experimentalRawEvents: false };
			response = await rpc.request<ThreadStartResponse>("thread/start", params);
		}
		this.sessionId = response.thread.id;
		this.emit({
			type: "session.started",
			sessionId: response.thread.id,
			model: response.model ?? null,
			authSource: null,
		});

		const first = await this.firstMessage(options);
		this.queue.unshift(first);
		this.ready = true;
		this.setState("running");
		this.pump();
	}

	private threadConfig(
		options: SessionStartOptions,
		sandbox: ThreadStartParams["sandbox"],
	): Record<string, string[]> | null {
		const dirs = options.additionalDirectories?.length
			? options.additionalDirectories
			: [options.cwd];
		const roots = dirs
			.filter((dir): dir is string => typeof dir === "string" && dir.length > 0)
			.map((dir) => dir.replace(/\\/g, "/"));
		if (sandbox !== "workspace-write" || roots.length === 0) return null;
		return { "sandbox_workspace_write.writable_roots": [...new Set(roots)] };
	}

	/**
	 * The first turn: a skill step uses a native `skill` input when Codex has
	 * the skill (`skills/list`), else the inlined prompt. The choice is logged.
	 */
	private async firstMessage(options: SessionStartOptions): Promise<QueuedMessage> {
		const id = randomUUID();
		const images = options.images ?? [];
		const skill = options.skill;
		if (!skill) return { id, text: options.prompt, images };
		const native = await this.lookupSkill(skill, options.cwd ?? null);
		if (native) {
			this.emit({
				type: "notice",
				text: `Skill ${skill.id}: native Codex skill ${native.name} (${native.path})`,
			});
			const text = `$${native.name}${skill.text ? ` ${skill.text}` : ""}`;
			return { id, text, images, skill: native };
		}
		if (!options.prompt) {
			throw new Error(skill.fallbackError ?? `Skill '${skill.id}' was not found`);
		}
		this.emit({
			type: "notice",
			text: `Skill ${skill.id}: not in Codex skills/list, sending its SKILL.md inline`,
		});
		return { id, text: options.prompt, images };
	}

	private async lookupSkill(
		skill: SessionSkill,
		cwd: string | null,
	): Promise<{ name: string; path: string } | null> {
		try {
			const params: SkillsListParams = cwd ? { cwds: [cwd] } : {};
			const list = await (this.rpc as RpcClient).request<SkillsListResponse>("skills/list", params);
			return findCodexSkill(skill.id, list);
		} catch {
			return null;
		}
	}

	/** Starts the next turn when the session is ready, no turn runs and a message waits. */
	private pump(): void {
		if (!this.ready || this.closing || this.turnId || this.turnStarting) return;
		const next = this.queue.shift();
		if (!next || !this.rpc || !this.sessionId) return;
		// Messages queued while a turn ran are sent together as the next turn
		const batch = [next, ...this.queue.splice(0)];
		const input: UserInput[] = [];
		for (const message of batch) {
			if (message.skill) {
				input.push({ type: "skill", name: message.skill.name, path: message.skill.path });
			}
			input.push(...codexUserInput(message.text, message.images));
		}
		const params: TurnStartParams = { threadId: this.sessionId, input };
		this.turnStarting = true;
		this.turnText = null;
		if (this.state === "idle") this.setState("running");
		this.rpc.request<TurnStartResponse>("turn/start", params).then(
			(response) => {
				this.turnStarting = false;
				// turn/completed may already have arrived for a very short turn
				if (response.turn.status === "inProgress" && !this.completedTurns.has(response.turn.id)) {
					this.turnId = response.turn.id;
				} else {
					this.pump();
				}
			},
			(err: Error) => {
				this.turnStarting = false;
				this.emit({
					type: "turn.completed",
					result: `turn/start failed: ${err.message}`,
					isError: true,
					messageIds: batch.map((m) => m.id),
				});
				this.afterTurn();
			},
		);
	}

	private onNotification(method: string, params: unknown): void {
		switch (method) {
			case "turn/started": {
				const { turn } = params as TurnStartedNotification;
				if (!this.completedTurns.has(turn.id)) this.turnId = turn.id;
				return;
			}
			case "item/started":
			case "item/completed": {
				const { item } = params as ItemStartedNotification | ItemCompletedNotification;
				const done = method === "item/completed";
				if (done && item.type === "agentMessage") this.turnText = item.text;
				for (const event of codexItemEvents(item, done)) this.emit(event);
				return;
			}
			case "turn/completed": {
				const { turn } = params as TurnCompletedNotification;
				this.completedTurns.add(turn.id);
				this.turnId = null;
				const failed = turn.status === "failed";
				const result = this.turnText ?? (failed ? (turn.error?.message ?? "Turn failed") : "");
				this.emit({
					type: "turn.completed",
					result,
					isError: failed || (turn.status === "interrupted" && !this.turnText),
					messageIds: [],
				});
				this.turnText = null;
				this.afterTurn();
				return;
			}
			default:
				return;
		}
	}

	private afterTurn(): void {
		if (this.queue.length > 0) {
			this.pump();
			return;
		}
		if (this.pending.size === 0 && !this.closing) this.setState("idle");
	}

	private async onServerRequest(method: string, params: unknown): Promise<unknown> {
		switch (method) {
			case "item/commandExecution/requestApproval":
				return this.commandApproval(params as CommandExecutionRequestApprovalParams);
			case "item/fileChange/requestApproval":
				return this.fileChangeApproval(params as FileChangeRequestApprovalParams);
			case "item/permissions/requestApproval":
				return this.permissionsApproval(params as PermissionsRequestApprovalParams);
			case "item/tool/requestUserInput":
				return this.userInput(params as ToolRequestUserInputParams);
			case "mcpServer/elicitation/request": {
				const response: McpServerElicitationRequestResponse = {
					action: "decline",
					content: null,
					_meta: null,
				};
				return response;
			}
			default:
				throw new Error(`agentic-forge does not handle ${method}`);
		}
	}

	private async commandApproval(
		params: CommandExecutionRequestApprovalParams,
	): Promise<CommandExecutionRequestApprovalResponse> {
		const command = params.command ?? "";
		if (command && commandAllowed(command, this.options?.allowedTools)) {
			return { decision: "accept" };
		}
		const decision = await this.request({
			kind: "permission",
			question: `Allow ${SHELL_TOOL}? ${truncate(command || "(command not given)")}`,
			options: PERMISSION_OPTIONS,
			recommended: null,
			context: params.reason ?? "",
			tool: SHELL_TOOL,
			input: { command, ...(params.cwd ? { cwd: params.cwd } : {}) },
		});
		return { decision: isAllow(decision) ? "accept" : "decline" };
	}

	private async fileChangeApproval(
		params: FileChangeRequestApprovalParams,
	): Promise<FileChangeRequestApprovalResponse> {
		if (editsAllowed(this.options?.allowedTools)) return { decision: "accept" };
		const where = params.grantRoot ? ` under ${params.grantRoot}` : "";
		const decision = await this.request({
			kind: "permission",
			question: `Allow ${PATCH_TOOL}? File changes${where}`,
			options: PERMISSION_OPTIONS,
			recommended: null,
			context: params.reason ?? "",
			tool: PATCH_TOOL,
			input: { item: params.itemId, ...(params.grantRoot ? { grant_root: params.grantRoot } : {}) },
		});
		return { decision: isAllow(decision) ? "accept" : "decline" };
	}

	private async permissionsApproval(
		params: PermissionsRequestApprovalParams,
	): Promise<PermissionsRequestApprovalResponse> {
		const decision = await this.request({
			kind: "permission",
			question: `Allow ${PERMISSIONS_TOOL}? ${truncate(JSON.stringify(params.permissions))}`,
			options: PERMISSION_OPTIONS,
			recommended: null,
			context: params.reason ?? "",
			tool: PERMISSIONS_TOOL,
			input: { permissions: params.permissions, cwd: params.cwd },
		});
		if (!isAllow(decision)) return { permissions: {}, scope: "turn" };
		const granted: PermissionsRequestApprovalResponse["permissions"] = {};
		if (params.permissions.network) granted.network = params.permissions.network;
		if (params.permissions.fileSystem) granted.fileSystem = params.permissions.fileSystem;
		return { permissions: granted, scope: "turn" };
	}

	private async userInput(
		params: ToolRequestUserInputParams,
	): Promise<ToolRequestUserInputResponse> {
		const answers: ToolRequestUserInputResponse["answers"] = {};
		for (const q of params.questions) {
			const options = (q.options ?? []).slice(0, OPTION_IDS.length).map((o, i) => ({
				id: OPTION_IDS[i],
				label: o.label,
				...(o.description ? { description: o.description } : {}),
			}));
			const decision = await this.request({
				kind: "question",
				question: q.question,
				options,
				recommended: null,
				context: [q.header, q.isOther ? "A free-text answer is accepted" : ""]
					.filter(Boolean)
					.join(". "),
				tool: QUESTION_TOOL,
				input: { id: q.id, header: q.header, secret: q.isSecret },
			});
			const chosen = options.find((o) => o.id === decision.option);
			answers[q.id] = { answers: [chosen ? chosen.label : decision.text] };
		}
		return { answers };
	}

	private request(fields: Omit<SessionRequest, "id">): Promise<SessionDecision> {
		// Unique across sessions: parallel steps each raise requests in one run
		const id = `${fields.kind === "question" ? "ask" : "perm"}-${randomUUID().slice(0, 8)}`;
		const request: SessionRequest = { id, ...fields };
		return new Promise((resolve) => {
			this.pending.set(id, resolve);
			this.setState("awaiting-input");
			this.emit({ type: "request", request });
		});
	}

	private finish(): void {
		if (this.finished) return;
		this.finished = true;
		for (const id of [...this.pending.keys()]) {
			this.respond(id, { option: "deny", text: "Session ended" });
		}
		this.setState("closed");
		this.settle(this.failure);
	}

	private setState(state: SessionState): void {
		if (this.state === state || this.state === "closed") return;
		this.state = state;
		this.emit({ type: "state", state });
	}

	private emit(event: SessionEvent): void {
		try {
			this.listener(event);
		} catch {
			// A listener error must not break the session
		}
	}
}

function isAllow(decision: SessionDecision): boolean {
	if (decision.option === "allow") return true;
	if (decision.option === "deny") return false;
	return /^(allow|allowed|yes|y|approve|approved|ok)$/i.test(decision.text.trim());
}

function truncate(value: string): string {
	return value.length > 200 ? `${value.slice(0, 200)}...` : value;
}
